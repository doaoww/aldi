import type { Locale } from "./types";

// Коды ошибок стабильны и не зависят от языка; тексты — ниже, по языкам.
const CODES = {
  INVALID_INPUT: 400,
  UNSUPPORTED_LOCALE: 400,
  CONSENT_REQUIRED: 400,
  INVITATION_INVALID: 400,
  UNAUTHENTICATED: 401,
  INVALID_CREDENTIALS: 401,
  FORBIDDEN: 403,
  CSRF_REJECTED: 403,
  NOT_FOUND: 404,
  VERSION_CONFLICT: 409,
  LOGIN_TAKEN: 409,
  CARD_NOT_READY: 409,
  INTAKE_CLOSED: 409,
  EMPTY_CONVERSATION: 409,
  TRANSCRIPT_NOT_READY: 409,
  RATE_LIMITED: 429,
  INTERNAL: 500,
  LLM_UNAVAILABLE: 503,
  VOICE_UNAVAILABLE: 503,
} as const;
export type ErrorCode = keyof typeof CODES;

export class AppError extends Error {
  status: number;
  constructor(public code: ErrorCode, public details?: unknown) {
    super(code);
    this.status = CODES[code];
  }
}

